create or replace function public.cp_iso(ts timestamptz)
returns text
language sql
immutable
as $$
  select to_char(ts at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
$$;

-- ---------------------------------------------------------------------------
-- Booking (atomic, race-safe)
-- ---------------------------------------------------------------------------

create or replace function public.book_appointment(
  p_service_id bigint,
  p_date text,
  p_start text,
  p_patient_user_id bigint,
  p_name text,
  p_email text,
  p_phone text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_service public.services%rowtype;
  v_end text;
  v_auto boolean;
  v_status text;
  v_ref text;
  v_now text := public.cp_iso(now());
  v_conflict int;
  v_attempt int := 0;
begin
  select * into v_service from public.services where id = p_service_id;
  if not found then
    return jsonb_build_object('ok', false, 'code', 'service_missing',
      'reason', 'The selected service could not be found.');
  end if;
  if not v_service.is_active then
    return jsonb_build_object('ok', false, 'code', 'service_inactive',
      'reason', 'The selected service is not currently available for booking.');
  end if;

  v_end := to_char((p_start::time + make_interval(mins => v_service.duration_minutes)), 'HH24:MI');

  -- Serialise bookings for the same date so the overlap check is reliable.
  perform pg_advisory_xact_lock(hashtext('carepoint:book:' || p_date)::bigint);

  select count(*) into v_conflict
    from public.appointments
   where appointment_date = p_date
     and status in ('pending', 'confirmed', 'rescheduled', 'completed')
     and start_time < v_end
     and end_time > p_start;
  if v_conflict > 0 then
    return jsonb_build_object('ok', false, 'code', 'slot_taken',
      'reason', 'That time slot was just booked by someone else. Please choose another slot.');
  end if;

  select auto_confirm into v_auto from public.clinic_settings where id = 1;
  v_status := case when coalesce(v_auto, false) then 'confirmed' else 'pending' end;

  loop
    v_attempt := v_attempt + 1;
    v_ref := 'CP-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 8));
    begin
insert into public.appointments (
        reference, patient_user_id, patient_name, patient_email, patient_phone, reason, service_id,
        service_name, service_price, service_duration, appointment_date, start_time,
        end_time, status, cancellation_reason, created_at, updated_at
      ) values (
        v_ref, nullif(p_patient_user_id, 0), p_name, p_email, p_phone, nullif(p_reason, ''), v_service.id,
        v_service.name, v_service.price, v_service.duration_minutes, p_date, p_start,
        v_end, v_status, null, v_now, v_now
      );
      exit;
    exception when unique_violation then
      if v_attempt >= 6 then
        return jsonb_build_object('ok', false, 'code', 'slot_taken',
          'reason', 'That time slot was just booked by someone else. Please choose another slot.');
      end if;
    end;
  end loop;

  return jsonb_build_object('ok', true, 'reference', v_ref,
    'autoConfirmed', coalesce(v_auto, false));
end;
$$;

create or replace function public.reschedule_appointment(
  p_id bigint,
  p_date text,
  p_start text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_appt public.appointments%rowtype;
  v_end text;
  v_conflict int;
begin
  select * into v_appt from public.appointments where id = p_id;
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'Appointment not found.');
  end if;
  if v_appt.status = 'cancelled' then
    return jsonb_build_object('ok', false, 'reason', 'Cancelled appointments cannot be rescheduled.');
  end if;

  v_end := to_char((p_start::time + make_interval(mins => v_appt.service_duration)), 'HH24:MI');

  perform pg_advisory_xact_lock(hashtext('carepoint:book:' || p_date)::bigint);

  select count(*) into v_conflict
    from public.appointments
   where appointment_date = p_date
     and status in ('pending', 'confirmed', 'rescheduled', 'completed')
     and id <> p_id
     and start_time < v_end
     and end_time > p_start;
  if v_conflict > 0 then
    return jsonb_build_object('ok', false, 'reason', 'That slot is no longer available.');
  end if;

  update public.appointments
     set appointment_date = p_date,
         start_time = p_start,
         end_time = v_end,
         status = 'rescheduled',
         updated_at = public.cp_iso(now())
   where id = p_id;

  return jsonb_build_object('ok', true);
end;
$$;

