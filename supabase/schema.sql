create or replace function public.register_patient(p_name text, p_email text, p_password text, p_phone text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_user public.patient_users%rowtype;
  v_token text;
  v_expires timestamptz := now() + interval '8 hours';
begin
  if exists (select 1 from public.patient_users where lower(email) = lower(p_email)) then
    return jsonb_build_object('ok', false, 'code', 'email_taken',
      'reason', 'An account already exists for that email address.');
  end if;

  insert into public.patient_users (name, email, password_hash, phone, created_at, updated_at)
  values (p_name, lower(p_email), crypt(p_password, gen_salt('bf')), p_phone,
          public.cp_iso(now()), public.cp_iso(now()))
  returning * into v_user;

  v_token := encode(gen_random_bytes(32), 'hex');
  insert into public.patient_sessions (id, patient_user_id, token_hash, created_at, expires_at)
  values (encode(gen_random_bytes(16), 'hex'), v_user.id,
          encode(digest(v_token, 'sha256'), 'hex'),
          public.cp_iso(now()), public.cp_iso(v_expires));

  return jsonb_build_object(
    'ok', true,
    'token', v_token,
    'expires_at', public.cp_iso(v_expires),
    'patient', jsonb_build_object(
      'id', v_user.id, 'name', v_user.name, 'email', v_user.email,
      'phone', v_user.phone, 'created_at', v_user.created_at, 'updated_at', v_user.updated_at
    )
  );
end;
$$;

