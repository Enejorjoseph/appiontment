create table if not exists public.services (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price integer not null check (price >= 0),
  duration_minutes integer not null check (duration_minutes > 0),
  is_active boolean not null default true,
  created_at text not null,
  updated_at text not null
);

create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null default 'staff' check (role in ('admin', 'staff')),
  created_at text not null,
  updated_at text not null
);

create table if not exists public.admin_sessions (
  id text primary key,
  admin_user_id bigint not null references public.admin_users (id) on delete cascade,
  token_hash text not null,
  created_at text not null,
  expires_at text not null
);
create index if not exists idx_admin_sessions_user on public.admin_sessions (admin_user_id);

create table if not exists public.patient_users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  phone text not null default '',
  created_at text not null,
  updated_at text not null
);

create table if not exists public.patient_sessions (
  id text primary key,
  patient_user_id bigint not null references public.patient_users (id) on delete cascade,
  token_hash text not null,
  created_at text not null,
  expires_at text not null
);
create index if not exists idx_patient_sessions_user on public.patient_sessions (patient_user_id);

create table if not exists public.clinic_settings (
  id integer primary key check (id = 1),
  clinic_name text not null,
  tagline text not null default '',
  description text not null default '',
  phone text not null default '',
  email text not null default '',
  address text not null default '',
  timezone text not null default 'Africa/Lagos',
  slot_interval_minutes integer not null default 30 check (slot_interval_minutes > 0),
  min_notice_minutes integer not null default 60 check (min_notice_minutes >= 0),
  max_booking_days integer not null default 60 check (max_booking_days > 0),
  auto_confirm boolean not null default false,
  cancellation_policy text not null default '',
  updated_at text not null
);

create table if not exists public.working_hours (
  id bigint generated by default as identity primary key,
  weekday integer not null check (weekday between 0 and 6),
  is_open boolean not null default true,
  open_time text,
  close_time text,
  break_start text,
  break_end text,
  unique (weekday)
);

create table if not exists public.blocked_periods (
  id bigint generated by default as identity primary key,
  date text not null,
  start_time text,
  end_time text,
  reason text not null default '',
  created_by bigint references public.admin_users (id) on delete set null,
  created_at text not null,
  check (start_time is null or end_time is null or start_time < end_time)
);
create index if not exists idx_blocked_periods_date on public.blocked_periods (date);

create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  patient_user_id bigint references public.patient_users (id) on delete set null,
  patient_name text not null,
  patient_email text not null,
  patient_phone text not null,
  reason text,
  service_id bigint references public.services (id) on delete set null,
  service_name text not null,
  service_price integer not null,
  service_duration integer not null,
  appointment_date text not null,
  start_time text not null,
  end_time text not null,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'cancelled', 'completed', 'rescheduled')),
  cancellation_reason text,
  created_at text not null,
  updated_at text not null,
  check (end_time > start_time)
);
-- Keep existing databases in sync without wiping data.
