-- CarePoint Clinic — Supabase (Postgres) schema, security and seed data.
--
-- Run this once in the Supabase Dashboard → SQL Editor for the project that
-- NEXT_PUBLIC_SUPABASE_URL points at. It is safe to run again: tables use
-- IF NOT EXISTS, policies are dropped and recreated, functions are replaced,
-- and seed data only inserts when the services table is empty.
--
-- Security model
--   * The app talks to Postgres with the publishable (anon) key.
--   * Application tables (services, clinic_settings, working_hours,
--     blocked_periods, appointments, contact_messages) allow anon access so the
--     server can read/write them. This is convenient for a demo; for production
--     use a service-role key on the server and tighten these policies.
--   * admin_users / admin_sessions have RLS enabled with NO policies, so their
--     contents (password hashes, session tokens) are never exposed directly.
--     Authentication runs through SECURITY DEFINER functions instead.

create extension if not exists pgcrypto;

