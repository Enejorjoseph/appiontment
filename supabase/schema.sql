create or replace function public.login_admin(p_email text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_user public.admin_users%rowtype;
  v_token text;
  v_expires timestamptz := now() + interval '8 hours';
begin
  select * into v_user from public.admin_users
   where lower(email) = lower(p_email)
   limit 1;
  if not found then
    return jsonb_build_object('ok', false);
  end if;
  if v_user.password_hash <> crypt(p_password, v_user.password_hash) then
    return jsonb_build_object('ok', false);
  end if;

  v_token := encode(gen_random_bytes(32), 'hex');

  insert into public.admin_sessions (id, admin_user_id, token_hash, created_at, expires_at)
  values (encode(gen_random_bytes(16), 'hex'), v_user.id,
          encode(digest(v_token, 'sha256'), 'hex'),
          public.cp_iso(now()), public.cp_iso(v_expires));

  return jsonb_build_object(
    'ok', true,
    'token', v_token,
    'expires_at', public.cp_iso(v_expires),
    'admin', jsonb_build_object(
      'id', v_user.id,
      'name', v_user.name,
      'email', v_user.email,
      'role', v_user.role,
      'created_at', v_user.created_at,
      'updated_at', v_user.updated_at
    )
  );
end;
$$;

create or replace function public.current_admin(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_row record;
begin
  select u.id, u.name, u.email, u.role, u.created_at, u.updated_at,
         s.id as session_id, s.expires_at
    into v_row
    from public.admin_sessions s
    join public.admin_users u on u.id = s.admin_user_id
   where s.token_hash = encode(digest(p_token, 'sha256'), 'hex');
  if not found then
    return null;
  end if;
  if v_row.expires_at::timestamptz <= now() then
    delete from public.admin_sessions where id = v_row.session_id;
    return null;
  end if;
  return jsonb_build_object(
    'id', v_row.id, 'name', v_row.name, 'email', v_row.email,
    'role', v_row.role, 'created_at', v_row.created_at, 'updated_at', v_row.updated_at
  );
end;
$$;

